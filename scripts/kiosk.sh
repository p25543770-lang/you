#!/usr/bin/env bash
#
# Бортовой экран робота (киоск, порт 8090) одной командой.
#
#   ./scripts/kiosk.sh              # сервер на 8090 + экран в браузере без рамок
#   ./scripts/kiosk.sh --no-open    # только сервер (для службы/без дисплея)
#   ./scripts/kiosk.sh --source sim # стенд: данные симуляции
#
# Что делает: подтягивает зависимости (офлайн из vendor/, если сети нет) и
# запускает run_kiosk.py, который:
#   * поднимает сервер на 8090, если порт свободен;
#   * дожидается ответа сервера и открывает экран в браузере в киоск-режиме;
#   * снова открывает экран, если браузер закрыли (см. RC_KIOSK_WATCHDOG).
#
# Если сервер на 8090 уже запущен (например, службой robot-kiosk), команда
# просто открывает экран — второй сервер не поднимается.
#
# Остановка: Ctrl+C в этом окне (или ./scripts/stop.sh).
#
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ "${RC_SKIP_DEPS:-0}" != "1" ]]; then
  ./scripts/ensure_deps.sh
fi
exec .venv/bin/python run_kiosk.py "$@"
