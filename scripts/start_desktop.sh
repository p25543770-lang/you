#!/usr/bin/env bash
# Обёртка для ярлыка «Робот-пульт»: запускает start.sh и НЕ даёт терминалу
# закрыться, пока не нажмёте Enter — видно и успешный запуск, и ошибку.
# Сервер живёт, пока открыто окно: закрыли окно / Ctrl+C — сервер остановился.
DIR="$(cd "$(dirname "$0")" && pwd)"

"$DIR/start.sh"
STATUS=$?

echo
if [[ $STATUS -ne 0 ]]; then
  echo "⚠ Сервер остановился с ошибкой (код $STATUS). Текст выше — причина."
  echo "  Частые причины: нет сети для git/pip, старый Python, занят порт."
else
  echo "✔ Сервер остановлен корректно."
fi
echo
read -r -p "Нажмите Enter, чтобы закрыть окно…"
